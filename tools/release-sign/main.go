// release-sign signs one release artifact in Irrigator's update format
// (irrigator.update/v1; see docs/update-verification.md and
// internal/selfupdate/update_verify.go). It writes release.json, the canonical
// json.Marshal bytes of the manifest, and release.sig, a raw 64-byte Ed25519
// signature over exactly those bytes.
//
// It never generates, stores or prints a key. The private key is read from the
// path given with -key: a raw 64-byte Ed25519 private key held outside the
// repository. Nothing is published or uploaded.
package main

import (
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"time"
)

const (
	manifestSchema = "irrigator.update/v1"
	artifactLimit  = int64(512 * 1024 * 1024)
	manifestLimit  = 4096
)

var versionPattern = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$`)

// updateManifest mirrors UpdateManifest in internal/selfupdate/update_verify.go. The
// field order is the wire order and must not change independently of it.
type updateManifest struct {
	Schema         string `json:"schema"`
	Sequence       uint64 `json:"sequence"`
	Version        string `json:"version"`
	OS             string `json:"os"`
	Arch           string `json:"arch"`
	ExpiresAt      string `json:"expires_at"`
	ArtifactSHA256 string `json:"artifact_sha256"`
	ArtifactBytes  int64  `json:"artifact_bytes"`
}

type options struct {
	keyPath      string
	artifactPath string
	version      string
	goos         string
	goarch       string
	sequence     uint64
	validFor     time.Duration
	outDir       string
}

func main() {
	var o options
	fs := flag.NewFlagSet("release-sign", flag.ContinueOnError)
	fs.StringVar(&o.keyPath, "key", "", "path to a raw 64-byte Ed25519 private key (never generated by this tool)")
	fs.StringVar(&o.artifactPath, "artifact", "", "artifact to sign")
	fs.StringVar(&o.version, "version", "", "release version without a leading v, for example 1.0.1")
	fs.StringVar(&o.goos, "os", "", "target GOOS: darwin or linux")
	fs.StringVar(&o.goarch, "arch", "", "target GOARCH: amd64 or arm64")
	fs.Uint64Var(&o.sequence, "sequence", 0, "monotonic release sequence, at least 1")
	fs.DurationVar(&o.validFor, "valid-for", 30*24*time.Hour, "how long the manifest stays valid")
	fs.StringVar(&o.outDir, "out", ".", "existing directory for release.json and release.sig")
	if err := fs.Parse(os.Args[1:]); err != nil {
		os.Exit(2)
	}
	if fs.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "release-sign: unexpected arguments")
		os.Exit(2)
	}
	if err := run(o, time.Now()); err != nil {
		fmt.Fprintln(os.Stderr, "release-sign:", err)
		os.Exit(1)
	}
}

func run(o options, now time.Time) error {
	if o.keyPath == "" || o.artifactPath == "" {
		return errors.New("-key and -artifact are required")
	}
	if !versionPattern.MatchString(o.version) || len(o.version) > 80 {
		return errors.New("invalid -version")
	}
	if (o.goos != "darwin" && o.goos != "linux") || (o.goarch != "amd64" && o.goarch != "arm64") {
		return errors.New("-os must be darwin or linux and -arch amd64 or arm64")
	}
	if o.sequence == 0 {
		return errors.New("-sequence must be at least 1")
	}
	if o.validFor <= 0 {
		return errors.New("-valid-for must be positive")
	}
	key, err := readKey(o.keyPath)
	if err != nil {
		return err
	}
	digest, size, err := hashArtifact(o.artifactPath)
	if err != nil {
		return err
	}
	m := updateManifest{
		Schema:         manifestSchema,
		Sequence:       o.sequence,
		Version:        o.version,
		OS:             o.goos,
		Arch:           o.goarch,
		ExpiresAt:      now.Add(o.validFor).UTC().Truncate(time.Second).Format(time.RFC3339),
		ArtifactSHA256: digest,
		ArtifactBytes:  size,
	}
	raw, err := json.Marshal(m)
	if err != nil {
		return err
	}
	if len(raw) > manifestLimit {
		return errors.New("manifest exceeds the verifier bound")
	}
	if st, err := os.Stat(o.outDir); err != nil || !st.IsDir() {
		return errors.New("-out must be an existing directory")
	}
	sig := ed25519.Sign(key, raw)
	if !ed25519.Verify(key.Public().(ed25519.PublicKey), raw, sig) {
		return errors.New("private key is not a consistent Ed25519 key")
	}
	if err := os.WriteFile(filepath.Join(o.outDir, "release.json"), raw, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(o.outDir, "release.sig"), sig, 0o644)
}

func readKey(path string) (ed25519.PrivateKey, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	b, err := io.ReadAll(io.LimitReader(f, ed25519.PrivateKeySize+1))
	if err != nil {
		return nil, err
	}
	if len(b) != ed25519.PrivateKeySize {
		return nil, errors.New("key must be a raw 64-byte Ed25519 private key")
	}
	return ed25519.PrivateKey(b), nil
}

func hashArtifact(path string) (string, int64, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", 0, err
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		return "", 0, err
	}
	if !st.Mode().IsRegular() || st.Size() <= 0 || st.Size() > artifactLimit {
		return "", 0, errors.New("artifact must be a non-empty regular file within the verifier size bound")
	}
	h := sha256.New()
	n, err := io.Copy(h, io.LimitReader(f, artifactLimit+1))
	if err != nil {
		return "", 0, err
	}
	if n != st.Size() {
		return "", 0, errors.New("artifact changed while hashing")
	}
	return hex.EncodeToString(h.Sum(nil)), n, nil
}
